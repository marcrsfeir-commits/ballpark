// Makes any static web game work offline: writes <dir>/sw.js that precaches every file the site serves.
//   node make-offline.mjs <dir> [cache-name]
// In a git repo only tracked files are cached (= what GitHub Pages serves); otherwise the folder is walked.
// Google Fonts / CDN files linked from the HTML are precached too (font CSS is fetched and its font files cached).
// Register it from the page:  if ('serviceWorker' in navigator) navigator.serviceWorker.register('sw.js');
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { execFileSync } from 'child_process';

const root = path.resolve(process.argv[2] || '.');
const name = (process.argv[3] || path.basename(root)).toLowerCase().replace(/[^a-z0-9-]/g, '-');
const SKIP_DIRS = new Set(['.git', 'node_modules', 'tools', '.claude', '__pycache__', '.venv', 'env', 'venv']);
const SKIP = /(^|\/)(sw\.js|server\.js|serve\.js|start\.cmd|[^/]*\.md|\.gitignore|\.nojekyll|[^/]*\.log|[^/]*\.py|package(-lock)?\.json)$/i;
const CDN = /https:\/\/(fonts\.googleapis\.com|cdnjs\.cloudflare\.com|cdn\.jsdelivr\.net|unpkg\.com)\/[^"'\s)<>]+/g;

let files;
if (fs.existsSync(path.join(root, '.git'))) {
  files = execFileSync('git', ['-c', 'core.quotepath=off', 'ls-files'], { cwd: root, encoding: 'utf8' }).split('\n').filter(Boolean);
} else {
  files = [];
  (function walk(dir) {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) { if (!SKIP_DIRS.has(e.name)) walk(p); }
      else files.push(path.relative(root, p).split(path.sep).join('/'));
    }
  })(root);
}
files = files.filter(f => !SKIP.test(f) && !f.split('/').some(d => SKIP_DIRS.has(d)) && fs.existsSync(path.join(root, f))).sort();

const external = new Set();
for (const f of files.filter(f => /\.html?$/i.test(f))) {
  const html = fs.readFileSync(path.join(root, f), 'utf8');
  // only <link>/<script> references — not URLs that merely appear in comments or licence text
  for (const tag of html.match(/<(link|script)\b[^>]*>/gi) || []) for (const u of tag.match(CDN) || []) external.add(u.replace(/&amp;/g, '&'));
}

const hash = crypto.createHash('sha1');
for (const f of files) { hash.update(f); hash.update(fs.readFileSync(path.join(root, f))); }
const version = `${name}-${hash.digest('hex').slice(0, 12)}`;
const urls = [...new Set(['./', ...files.map(f => './' + encodeURI(f)),
  ...files.filter(f => /(^|\/)index\.html$/.test(f)).map(f => './' + encodeURI(f.replace(/index\.html$/, ''))).filter(u => u !== './')])];
const bytes = files.reduce((s, f) => s + fs.statSync(path.join(root, f)).size, 0);

fs.writeFileSync(path.join(root, 'sw.js'), `// Offline service worker — generated by make-offline.mjs (do not edit by hand; re-run it after changing files).
const VERSION = '${version}';
const PREFIX = '${name}-';
const FILES = ${JSON.stringify(urls)};
const EXTERNAL = ${JSON.stringify([...external])};
const CDN = /fonts\\.(googleapis|gstatic)\\.com|cdnjs\\.cloudflare\\.com|cdn\\.jsdelivr\\.net|unpkg\\.com/;

async function cacheExternal(cache) {
  for (const u of EXTERNAL) {
    try {
      const res = await fetch(u, { mode: 'cors' });
      if (!res.ok) continue;
      await cache.put(u, res.clone());
      if (/fonts\\.googleapis\\.com/.test(u)) {
        const css = await res.text();
        const fonts = [...css.matchAll(/url\\((https:[^)]+)\\)/g)].map(m => m[1]);
        await Promise.all(fonts.map(f => fetch(f, { mode: 'cors' }).then(r => r.ok && cache.put(f, r)).catch(() => {})));
      }
    } catch (e) { /* online-only extra; the game still works without it */ }
  }
}
self.addEventListener('install', e => {
  e.waitUntil(caches.open(VERSION).then(c => c.addAll(FILES).then(() => cacheExternal(c))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith(PREFIX) && k !== VERSION).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const req = e.request, url = new URL(req.url);
  if (req.method !== 'GET' || url.pathname.includes('/api/')) return;
  const sameOrigin = url.origin === location.origin;
  if (!sameOrigin && !CDN.test(url.host)) return; // multiplayer / accounts / analytics stay online-only
  e.respondWith(caches.open(VERSION).then(async cache => {
    const hit = await cache.match(req, { ignoreSearch: sameOrigin, ignoreVary: true });
    const net = fetch(req).then(res => { if (res.ok || res.type === 'opaque') cache.put(req, res.clone()); return res; }).catch(() => null);
    if (hit) { e.waitUntil(net); return hit; }
    const res = await net;
    if (res) return res;
    if (req.mode === 'navigate') return (await cache.match('./index.html')) || Response.error();
    return Response.error();
  }));
});
`);
console.log(`${path.basename(root)}/sw.js: ${version}, ${files.length} files (${(bytes / 1048576).toFixed(1)} MB) + ${external.size} external`);
