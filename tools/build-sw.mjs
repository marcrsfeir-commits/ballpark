// Generates sw.js: a service worker that precaches every file of the site so BALLPARK works fully offline.
// Run before every push: node tools/build-sw.mjs   (the version is a content hash, so any change ships a fresh cache)
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { fileURLToPath } from 'url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const SKIP_DIRS = new Set(['.git', 'tools', 'node_modules', '.claude']);
const SKIP_FILES = new Set(['sw.js', 'version.json', 'serve.js', 'README.md', 'GAME_SPEC.md', '.gitignore']);
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (!SKIP_DIRS.has(e.name)) walk(p); }
    else if (!SKIP_FILES.has(e.name) && !e.name.endsWith('.log')) files.push(path.relative(root, p).split(path.sep).join('/'));
  }
})(root);
files.sort();

const hash = crypto.createHash('sha1');
for (const f of files) { hash.update(f); hash.update(fs.readFileSync(path.join(root, f))); }
const version = 'ballpark-' + hash.digest('hex').slice(0, 12);
// pages are also requested as folder URLs ("games/fuse/"), so cache those forms too
const urls = ['./', ...files.map(f => './' + f), ...files.filter(f => f.endsWith('/index.html') || f === 'index.html').map(f => './' + f.replace(/index\.html$/, '')).filter(u => u !== './')];
// version.json: the subtle build label on the hub (not hashed, so an unchanged site keeps its version)
const now = new Date(), pad = n => String(n).padStart(2, '0');
fs.writeFileSync(path.join(root, 'version.json'), JSON.stringify({ v: version.slice(9, 16), built: `${now.getFullYear()}.${pad(now.getMonth() + 1)}.${pad(now.getDate())} ${pad(now.getHours())}:${pad(now.getMinutes())}` }));
const bytes = files.reduce((s, f) => s + fs.statSync(path.join(root, f)).size, 0);

const sw = `// BALLPARK offline service worker — generated by tools/build-sw.mjs, do not edit by hand.
const VERSION = '${version}';
const FILES = ${JSON.stringify([...new Set(urls)])};

self.addEventListener('install', e => {
  // install fast: only the code (pages, js, css, json) blocks the switch-over, so an update takes seconds, not 16 MB.
  // One file failing (flaky network) never throws the update away.
  e.waitUntil(caches.open(VERSION).then(c => fill(c, FILES.filter(f => isCode(f))))
    .then(() => self.skipWaiting()));

});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith('ballpark-') && k !== VERSION).map(k => caches.delete(k))))
    .then(() => self.clients.claim())
    .then(() => { caches.open(VERSION).then(c => fill(c, FILES.filter(f => !isCode(f)))); })); // images and sounds follow in the background
});
async function fill(c, list) {
  for (let i = 0; i < list.length; i += 40) await Promise.allSettled(list.slice(i, i + 40).map(async f => { if (!(await c.match(f))) await c.add(f); }));
}
// Code and data (pages, js, css, json) are network first so a push shows up on the next load; the cache is the
// offline fallback. Images, audio and fonts are cache first (instant), refreshed in the background.
// POSTs (local Fuse API) pass straight through.
const CODE = /(\\/|\\.html|\\.js|\\.mjs|\\.css|\\.json)$/, isCode = f => CODE.test(f);
self.addEventListener('fetch', e => {
  const req = e.request, url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin || url.pathname.includes('/api/')) return;
  e.respondWith(caches.open(VERSION).then(async cache => {
    if (req.mode === 'navigate' || CODE.test(url.pathname)) {
      const net = await Promise.race([fetch(req, { cache: 'no-cache' }).catch(() => null), new Promise(r => setTimeout(() => r(null), 4000))]);
      if (net && net.ok) { cache.put(req, net.clone()); return net; }
      const old = await cache.match(req, { ignoreSearch: true });
      if (old) return old;
      if (net) return net;
      if (req.mode === 'navigate') return (await cache.match('./index.html')) || Response.error();
      return Response.error();
    }
    const hit = await cache.match(req, { ignoreSearch: true });
    const net = fetch(req).then(res => { if (res.ok) cache.put(req, res.clone()); return res; }).catch(() => null);
    if (hit) return hit;
    const res = await net;
    if (res) return res;
    if (req.mode === 'navigate') return (await cache.match('./index.html')) || Response.error();
    return Response.error();
  }));
});
`;
fs.writeFileSync(path.join(root, 'sw.js'), sw);
console.log(`sw.js: ${version}, ${files.length} files, ${(bytes / 1048576).toFixed(1)} MB precached`);
