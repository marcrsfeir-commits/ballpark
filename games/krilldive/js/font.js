function glyph(ch) { return G[ch] || G[ch.toUpperCase()] || G['?']; }

export function measure(text, gap = 1) {
  let w = 0;
  for (const ch of text) w += glyph(ch)[0].length + gap;
  return Math.max(0, w - gap);
}

// Draw text into a canvas context at (x, y) in "font pixels" of size `px`.
export function drawText(g, text, x, y, px, color, gap = 1) {
  g.fillStyle = color;
  let cx = x;
  for (const ch of text) {
    const rows = glyph(ch);
    for (let r = 0; r < rows.length; r++) {
      const row = rows[r];
      for (let c = 0; c < row.length; c++) if (row[c] === '#') g.fillRect(cx + c * px, y + r * px, px, px);
    }
    cx += (rows[0].length + gap) * px;
  }
}

// Returns a canvas with the text rendered. opts: { px, color, chroma: [left, right], shadow, gap }
export function pixelText(text, opts = {}) {
  const px = opts.px || 4, gap = opts.gap ?? 1;
  const off = opts.chroma ? Math.max(1, Math.round(px / 2)) : 0;
  const shadow = opts.shadow ? px : 0;
  const w = measure(text, gap) * px + off * 2 + shadow;
  const h = 7 * px + shadow;
  const c = document.createElement('canvas');
  c.width = w; c.height = h;
  const g = c.getContext('2d');
  if (opts.shadow) drawText(g, text, off + shadow, shadow, px, opts.shadow, gap);
  if (opts.chroma) {
    g.globalCompositeOperation = 'lighter';
    drawText(g, text, 0, 0, px, opts.chroma[0], gap);
    drawText(g, text, off * 2, 0, px, opts.chroma[1], gap);
    g.globalCompositeOperation = 'source-over';
  }
  drawText(g, text, off, 0, px, opts.color || '#fff', gap);
  c.className = 'ptext';
  c.setAttribute('role', 'img');
  c.setAttribute('aria-label', text);
  return c;
}

// Replace an element's content with pixel text (keeps it accessible).
export function setPixelText(el, text, opts) {
  el.replaceChildren(pixelText(text, opts));
  el.setAttribute('aria-label', text);
}
